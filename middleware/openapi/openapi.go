// maxCachedSwaggerPages bounds the per-target Swagger UI page cache so that a
// parameterized mount prefix (one target per parameter value) cannot grow the
// cache without limit. The same bound applies to the per-app cache map.
const maxCachedSwaggerPages = 32

// maxPathVariants bounds the optional-parameter expansion in
// buildOpenAPIPathVariants, which is otherwise exponential in the number of
// optional parameters on a single route.
const maxPathVariants = 64

// appCache holds one app's generated artifacts. The spec bytes do not depend
// on the target path (only on the routes and config), so a single entry
// suffices no matter how many prefixes the handler serves; the Swagger UI
// pages embed the spec URL and stay keyed per target.
type appCache struct {
	uiPages  map[string][]byte
	specData []byte
	specRev  uint64
}

// New creates a new middleware handler that serves the generated OpenAPI specification.
func New(config ...Config) fiber.Handler {
	cfg := configDefault(config...)

	// Caches are scoped per *fiber.App: the same handler value may be
	// registered on several apps, and one app's spec or revision counter must
	// never validate another app's cached bytes.
	var (
		cacheMu sync.Mutex
		caches  = make(map[*fiber.App]*appCache)
	)

	// cacheFor returns the app's cache entry, creating it on first use. Past
	// the bound the entry is still returned but not retained. The caller must
	// hold cacheMu.
	cacheFor := func(app *fiber.App) *appCache {
		cache, ok := caches[app]
		if !ok {
			cache = &appCache{uiPages: make(map[string][]byte)}
			if len(caches) < maxCachedSwaggerPages {
				caches[app] = cache
			}
		}
		return cache
	}

	// specBytes returns the app's cached specification, regenerating it when the
	// route revision moved. The lock is released with defer so a panic in
	// GetRoutes, generateSpec or a user-supplied JSONEncoder cannot wedge the
	// cache for every app this handler serves.
	specBytes := func(app *fiber.App) ([]byte, error) {
		cacheMu.Lock()
		defer cacheMu.Unlock()

		cache := cacheFor(app)
		rev := app.RoutesRevision()
		if cache.specData == nil || cache.specRev != rev {
			// GetRoutes returns deep copies taken under the router lock, so
			// spec generation never races route registration or the
			// documentation helpers.
			spec := generateSpec(app.GetRoutes(), &cfg)
			data, err := app.Config().JSONEncoder(spec)
			if err != nil {
				return nil, fmt.Errorf("openapi: marshal spec: %w", err)
			}
			cache.specData, cache.specRev = data, rev
		}
		return cache.specData, nil
	}

	// uiBytes returns the app's cached Swagger UI page for targetPath, building
	// it on first use. Same defer rationale as specBytes.
	uiBytes := func(app *fiber.App, targetPath string) ([]byte, error) {
		cacheMu.Lock()
		defer cacheMu.Unlock()

		cache := cacheFor(app)
		if data, ok := cache.uiPages[targetPath]; ok {
			return data, nil
		}
		data, err := buildSwaggerUIPage(targetPath, &cfg, app.Config().JSONEncoder)
		if err != nil {
			return nil, fmt.Errorf("openapi: build swagger ui page: %w", err)
		}
		if len(cache.uiPages) >= maxCachedSwaggerPages {
			// The keys come from the request path under a parameterized mount,
			// so they are attacker-controlled; drop the oldest-inserted entries
			// rather than letting junk keys pin the cache and force a rebuild
			// on every later request.
			clear(cache.uiPages)
		}
		cache.uiPages[targetPath] = data
		return data, nil
	}

	specPath := utils.TrimRight(normalizedPath(cfg.Path), '/')
	uiPath := utils.TrimRight(normalizedPath(cfg.UIPath), '/')

	return func(c fiber.Ctx) error {
		if cfg.Next != nil && cfg.Next(c) {
			return c.Next()
		}

		if c.Method() != fiber.MethodGet && c.Method() != fiber.MethodHead {
			return c.Next()
		}

		equal := utils.EqualFold[string]
		if c.App().Config().CaseSensitive {
			equal = stringsEqual
		}

		request := utils.TrimRight(c.Path(), '/')
		route := c.Route()
		isMiddleware := route != nil && route.IsMiddleware()

		// Fast path for prefix-mounted middleware: most requests cannot match
		// either target, so skip target resolution without allocating.
		if isMiddleware && !hasSuffix(request, specPath, equal) && !hasSuffix(request, uiPath, equal) {
			return c.Next()
		}

		targets := resolveTargets(c, specPath, uiPath, equal)

		switch {
		case targets.specOK && equal(request, targets.spec):
			// The generated bytes are cached once per app and invalidated by
			// the app's route revision, so route additions, removals, and
			// metadata changes are always reflected without regenerating on
			// every request.
			data, err := specBytes(c.App())
			if err != nil {
				return err
			}

			c.Set(fiber.HeaderContentType, fiber.MIMEApplicationJSONCharsetUTF8)
			return c.Status(fiber.StatusOK).Send(data)
		case targets.uiOK && equal(request, targets.ui):
			data, err := uiBytes(c.App(), targets.spec)
			if err != nil {
				return err
			}

			c.Set(fiber.HeaderContentType, fiber.MIMETextHTMLCharsetUTF8)
			return c.Status(fiber.StatusOK).Send(data)
		default:
			return c.Next()
		}
	}
}

func stringsEqual(a, b string) bool { return a == b }

// hasSuffix reports whether s ends with suffix under the given equality
// function (exact or case-folding).
func hasSuffix(s, suffix string, equal func(a, b string) bool) bool {
	return len(s) >= len(suffix) && equal(s[len(s)-len(suffix):], suffix)
}

// specTargets holds the paths this handler answers on for the current request.
// The ok flags are explicit rather than encoded as an empty path, because an
// empty path is itself meaningful: it is what a root target ("/") trims to.
type specTargets struct {
	spec   string
	ui     string
	specOK bool
	uiOK   bool
}

// resolveTargets derives the spec and UI target paths (trailing slashes
// trimmed) for the current request from the route the handler runs on.
//
// For prefix middleware the targets live directly under the mount prefix, and a
// mount whose own prefix ends in a configured path IS that target. For an exact
// method route (e.g. app.Get("/openapi.json", openapi.New()), possibly cloned
// under a mount prefix) the registered path itself is the target: the
// configured suffix decides whether it serves the spec or the UI, and a fixed
// custom path matching neither serves the specification.
func resolveTargets(c fiber.Ctx, specPath, uiPath string, equal func(a, b string) bool) specTargets {
	route := c.Route()
	if route == nil {
		return specTargets{spec: specPath, ui: uiPath, specOK: true, uiOK: true}
	}

	if !route.IsMiddleware() {
		// The route matched exactly, so the request path IS the concrete
		// registered path — including values of any parameters the pattern
		// carries (e.g. an exact route cloned under a parameterized mount
		// prefix).
		path := utils.TrimRight(c.Path(), '/')
		switch {
		case specPath != "" && hasSuffix(path, specPath, equal):
			base := path[:len(path)-len(specPath)]
			return specTargets{spec: path, ui: base + uiPath, specOK: true, uiOK: uiPath != ""}
		case uiPath != "" && hasSuffix(path, uiPath, equal):
			base := path[:len(path)-len(uiPath)]
			return specTargets{spec: base + specPath, ui: path, specOK: true, uiOK: true}
		case len(route.Params) == 0:
			// A fixed custom path (app.Get("/docs", openapi.New())) serves the
			// specification.
			return specTargets{spec: path, specOK: true}
		default:
			// A wildcard or parameterized registration matches paths the author
			// never enumerated, so serving the document at every one of them
			// would leak the whole route inventory. Only the exact suffix
			// matches above are honored.
			return specTargets{}
		}
	}

	prefix := routePrefix(route.Path, c.Path())
	switch {
	case specPath != "" && hasSuffix(prefix, specPath, equal):
		// e.g. app.Use("/v1/openapi.json", openapi.New()): the mount itself is
		// the spec target; the UI, if enabled, sits beside it.
		base := prefix[:len(prefix)-len(specPath)]
		return specTargets{spec: prefix, ui: base + uiPath, specOK: true, uiOK: uiPath != ""}
	case uiPath != "" && hasSuffix(prefix, uiPath, equal):
		// e.g. app.Use("/swagger", openapi.New()): the mount itself is the UI.
		// The spec has to stay *under* the mount, otherwise the page that is
		// served here could never load the document it points at.
		return specTargets{spec: prefix + specPath, ui: prefix, specOK: true, uiOK: true}
	default:
		return specTargets{spec: prefix + specPath, ui: prefix + uiPath, specOK: true, uiOK: true}
	}
}

